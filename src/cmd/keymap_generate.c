#include "platform/keymap.h"

#include <stdio.h>

enum { INPUT_LIMIT = 4096 };

static int read_input(const char *path, char *text) {
    FILE *file = fopen(path, "rb");
    if (file == NULL) {
        fprintf(stderr, "%s: cannot read\n", path);
        return 0;
    }
    size_t length = fread(text, 1, INPUT_LIMIT + 1, file);
    int failed = ferror(file);
    fclose(file);
    if (failed) {
        fprintf(stderr, "%s: cannot read\n", path);
        return 0;
    }
    if (length > INPUT_LIMIT) {
        fprintf(stderr, "%s: larger than %d bytes\n", path, INPUT_LIMIT);
        return 0;
    }
    text[length] = '\0';
    return 1;
}

static void write_unit(FILE *out, const char *input_path, const keymap_t *keymap) {
    fprintf(out, "/* Generated by keymap_generate from %s. Do not edit. */\n", input_path);
    fprintf(out, "#include \"platform/keymap.h\"\n\n");
    fprintf(out, "const keymap_t keymap_compiled = { .buttons = {\n");
    for (int i = 0; i < P8_PAD_BUTTON_COUNT; i++) {
        const keymap_button_t *button = &keymap->buttons[i];
        fprintf(out, "    /* button %d */ { .bindings = {", i + 1);
        for (int j = 0; j < button->count; j++) {
            const char *device = button->bindings[j].device == KEYMAP_KEYBOARD ? "KEYMAP_KEYBOARD" : "KEYMAP_GAMEPAD";
            fprintf(out, "%s { %s, %d }", j == 0 ? "" : ",", device, button->bindings[j].code);
        }
        fprintf(out, " }, .count = %d },\n", button->count);
    }
    fprintf(out, "} };\n");
}

int main(int argc, char **argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: keymap_generate <input.cfg> <output.c>\n");
        return 2;
    }
    const char *input_path = argv[1];
    const char *output_path = argv[2];
    static char text[INPUT_LIMIT + 1];
    if (!read_input(input_path, text)) {
        return 1;
    }
    keymap_t keymap;
    keymap_error_t error;
    if (!keymap_parse(text, &keymap, &error)) {
        if (error.line > 0) {
            fprintf(stderr, "%s:%d: %s\n", input_path, error.line, error.message);
        } else {
            fprintf(stderr, "%s: %s\n", input_path, error.message);
        }
        return 1;
    }
    char temporary_path[4096];
    if (snprintf(temporary_path, sizeof temporary_path, "%s.tmp", output_path) >= (int)sizeof temporary_path) {
        fprintf(stderr, "%s: path too long\n", output_path);
        return 1;
    }
    FILE *out = fopen(temporary_path, "w");
    if (out == NULL) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        return 1;
    }
    write_unit(out, input_path, &keymap);
    int failed = ferror(out);
    if (fclose(out) != 0 || failed) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        remove(temporary_path);
        return 1;
    }
    if (rename(temporary_path, output_path) != 0) {
        fprintf(stderr, "%s: cannot rename to %s\n", temporary_path, output_path);
        remove(temporary_path);
        return 1;
    }
    return 0;
}
