#!/bin/sh
# Lists every pico8_value_t member of an entity struct typedef of src/:
# `typedef struct { ... } pico8_X_t;` whose first member is a
# pico8_struct_header_t, or a (non-pointer) entity typedef it embeds.
#
#   tools/entity_value_members.sh            file:line: typedef member, then
#                                            "membres pico8_value_t : N"; exit 0
#   tools/entity_value_members.sh --check    the same output; exit 1 if N > 0
#   tools/entity_value_members.sh --c-table  the C table that
#                                            src/pico8_member_census.c includes
#                                            under -DPICO8_MEMBER_CENSUS
#
# An array member prints as `a[]`. Phase 1b of docs/plan-3.md ends when the
# list is empty.
set -e

ROOT=$(dirname "$0")/..
cd "$ROOT"

MODE=list
if [ "$1" = "--c-table" ]; then
    MODE=ctable
elif [ "$1" = "--check" ]; then
    MODE=check
fi

LC_ALL=C
export LC_ALL

# shellcheck disable=SC2046
awk -v mode="$MODE" '
function strip_comments(line,    out, s, e) {
    out = ""
    while (length(line) > 0) {
        if (in_comment) {
            e = index(line, "*/")
            if (e == 0) {
                return out
            }
            line = substr(line, e + 2)
            in_comment = 0
            continue
        }
        s = index(line, "/*")
        e = index(line, "//")
        if (e > 0 && (s == 0 || e < s)) {
            return out substr(line, 1, e - 1)
        }
        if (s == 0) {
            return out line
        }
        out = out substr(line, 1, s - 1) " "
        line = substr(line, s + 2)
        in_comment = 1
    }
    return out
}
FNR == 1 {
    in_comment = 0
    in_td = 0
    nfiles++
}
{
    line = strip_comments($0)
    if (!in_td) {
        if (line ~ /^typedef struct[ \t]*\{[ \t]*$/) {
            in_td = 1
            depth = 1
            ntd++
            td_file[ntd] = FILENAME
            td_first[ntd] = ""
            td_first_ptr[ntd] = 0
            td_nmem[ntd] = 0
        }
        next
    }
    if (depth == 1 && line ~ /^\}[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*;/) {
        name = line
        sub(/^\}[ \t]*/, "", name)
        sub(/[ \t]*;.*$/, "", name)
        td_name[ntd] = name
        td_index[name] = ntd
        in_td = 0
        next
    }
    opens = gsub(/\{/, "{", line)
    closes = gsub(/\}/, "}", line)
    if (depth != 1) {
        depth += opens - closes
        next
    }
    depth += opens - closes
    if (line ~ /^[ \t]*$/ || line ~ /^[ \t]*#/) {
        next
    }
    decl = line
    sub(/^[ \t]+/, "", decl)
    sub(/[ \t]*;.*$/, "", decl)
    if (opens > 0) {
        if (td_first[ntd] == "") {
            td_first[ntd] = "(nested)"
        }
        next
    }
    type = decl
    sub(/^(const[ \t]+)?/, "", type)
    rest = type
    sub(/[ \t*].*$/, "", type)
    rest = substr(rest, length(type) + 1)
    if (td_first[ntd] == "") {
        td_first[ntd] = type
        td_first_ptr[ntd] = (rest ~ /^[ \t]*\*/)
        td_first_name[ntd] = rest
        gsub(/[ \t*]/, "", td_first_name[ntd])
    }
    if (type != "pico8_value_t") {
        next
    }
    n = split(rest, parts, ",")
    for (i = 1; i <= n; i++) {
        d = parts[i]
        gsub(/[ \t]/, "", d)
        if (d ~ /^\*/) {
            continue
        }
        if (d ~ /\[/) {
            sub(/\[.*$/, "", d)
            d = d "[]"
        }
        td_nmem[ntd]++
        mem_name[ntd, td_nmem[ntd]] = d
        mem_line[ntd, td_nmem[ntd]] = FNR
    }
}
END {
    changed = 1
    while (changed) {
        changed = 0
        for (t = 1; t <= ntd; t++) {
            if (is_entity[t]) {
                continue
            }
            f = td_first[t]
            if (f == "pico8_struct_header_t" && !td_first_ptr[t]) {
                is_entity[t] = 1
                parent[t] = 0
                changed = 1
            } else if ((f in td_index) && is_entity[td_index[f]] && !td_first_ptr[t]) {
                is_entity[t] = 1
                parent[t] = td_index[f]
                changed = 1
            }
        }
    }
    if (mode == "list" || mode == "check") {
        total = 0
        for (t = 1; t <= ntd; t++) {
            if (!is_entity[t]) {
                continue
            }
            for (m = 1; m <= td_nmem[t]; m++) {
                printf "%s:%d: %s %s\n", td_file[t], mem_line[t, m], td_name[t], mem_name[t, m]
                total++
            }
        }
        printf "membres pico8_value_t : %d\n", total
        exit (mode == "check" && total > 0)
    }
    print "/* Generated by tools/entity_value_members.sh --c-table; never edit. */"
    for (t = 1; t <= ntd; t++) {
        if (is_entity[t] && td_file[t] ~ /\.h$/ && !(td_file[t] in included)) {
            included[td_file[t]] = 1
            hdr = td_file[t]
            sub(/^src\//, "", hdr)
            printf "#include \"%s\"\n", hdr
        }
    }
    k = 0
    for (t = 1; t <= ntd; t++) {
        if (is_entity[t]) {
            census_index[t] = k++
        }
    }
    print "static const pico8_member_census_typedef_t g_census_typedefs[] = {"
    for (t = 1; t <= ntd; t++) {
        if (is_entity[t]) {
            printf "    {\"%s\", %d, %d},\n", td_name[t], parent[t] ? census_index[parent[t]] : -1, td_file[t] ~ /\.c$/
        }
    }
    print "};"
    print "static const pico8_member_census_member_t g_census_members[] = {"
    nm = 0
    for (t = 1; t <= ntd; t++) {
        if (!is_entity[t]) {
            continue
        }
        for (m = 1; m <= td_nmem[t]; m++) {
            by_name = td_file[t] ~ /\.c$/ || mem_name[t, m] ~ /\[\]$/
            printf "    {%d, \"%s\", %s, %d},\n", census_index[t], mem_name[t, m], \
                by_name ? "0" : "offsetof(" td_name[t] ", " mem_name[t, m] ")", by_name
            nm++
        }
    }
    if (nm == 0) {
        print "    {-1, \"\", 0, 1},"
    }
    print "};"
    printf "#define PICO8_MEMBER_CENSUS_MEMBER_COUNT %d\n", nm
}
' $(ls src/*.c src/*.h | sort)
