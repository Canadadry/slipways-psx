/* Host tool behind make sprite-sheet: writes src/p8/sprite_sheet_packed.h on
 * stdout from the sheet that p8_load_gfx_json reads, or nothing on failure. */
#include "p8/assets.h"
#include "p8/vram.h"

#include <stdio.h>

#define PACKED_SIZE (P8_SPRITE_SHEET_WIDTH * P8_SPRITE_SHEET_HEIGHT / 2)

int main(int argc, char **argv) {
    static p8_vram_t mem;
    static unsigned char packed[PACKED_SIZE];
    if (argc != 2) {
        fputs("usage: gen_sprite_sheet <gfx.json>\n", stderr);
        return 2;
    }
    const char *path = argv[1];

    p8_vram_init(&mem);
    if (!p8_load_gfx_json(&mem, path)) {
        fprintf(stderr, "gen_sprite_sheet: %s: load failed\n", path);
        return 1;
    }
    for (int y = 0; y < P8_SPRITE_SHEET_HEIGHT; y++) {
        for (int x = 0; x < P8_SPRITE_SHEET_WIDTH; x++) {
            unsigned char value = mem.sprite_sheet[y][x];
            if (value > 15) {
                fprintf(stderr, "gen_sprite_sheet: %s: pixel (%d, %d) is %d, above 15\n", path, x, y, value);
                return 1;
            }
            int index = y * (P8_SPRITE_SHEET_WIDTH / 2) + x / 2;
            packed[index] = (unsigned char)(packed[index] | (x % 2 == 0 ? value : value << 4));
        }
    }

    printf("/* Generated by tools/gen_sprite_sheet.c (make sprite-sheet) from pico8/gfx.json; do not edit by hand. */\n");
    printf("#ifndef P8_SPRITE_SHEET_PACKED_H\n");
    printf("#define P8_SPRITE_SHEET_PACKED_H\n\n");
    printf("static const unsigned char p8_sprite_sheet_packed_bytes[%d] = {\n", PACKED_SIZE);
    for (int i = 0; i < PACKED_SIZE; i++) {
        printf("%s0x%02X,", (i % 16 == 0) ? "    " : " ", packed[i]);
        if (i % 16 == 15) {
            printf("\n");
        }
    }
    printf("};\n\n#endif\n");
    return 0;
}
